CREATE OR REPLACE FUNCTION public.get_attendance_history(
    p_employee_id bigint DEFAULT NULL::bigint,
    p_from_date date DEFAULT NULL::date,
    p_to_date date DEFAULT NULL::date
)
RETURNS TABLE(
    employee_id bigint,
    attendance_date date,
    attendance_status integer,
    status_name text,
    check_in_time timestamp without time zone,
    check_out_time timestamp without time zone,
    check_in_latitude numeric,
    check_in_longitude numeric,
    check_in_distance_meters numeric,
    check_out_latitude numeric,
    check_out_longitude numeric,
    check_out_distance_meters numeric,
    worked_minutes integer,
    is_late boolean,
    late_minutes integer,
    is_early_departure boolean,
    early_departure_minutes integer,
    ot_minutes integer,
    leave_type_id bigint,
    leave_type_name text,
    holiday_id bigint,
    holiday_name text
)
LANGUAGE plpgsql
AS $function$
DECLARE
    v_from_date DATE;
    v_to_date DATE;
BEGIN
    v_from_date := COALESCE(p_from_date, CURRENT_DATE);
    v_to_date   := COALESCE(p_to_date, CURRENT_DATE);

    IF v_from_date > v_to_date THEN
        RAISE EXCEPTION 'From date cannot be greater than To date.';
    END IF;

    RETURN QUERY
    WITH employee_list AS (
        SELECT e."Id" AS employee_id
        FROM public."Employee" e
        WHERE e."IsActive" = TRUE
          AND (p_employee_id IS NULL OR e."Id" = p_employee_id)
    ),
    date_series AS (
        SELECT d::date AS att_date
        FROM generate_series(v_from_date, v_to_date, INTERVAL '1 day') AS d
    ),
    grid AS (
        SELECT el.employee_id, ds.att_date
        FROM employee_list el
        CROSS JOIN date_series ds
    ),
    leave_data AS (
        SELECT lr."EmployeeId" AS employee_id,
               d::date AS leave_date,
               lr."LeaveTypeId" AS leave_type_id,
               lt."Name"::text AS leave_type_name
        FROM public."LeaveRequest" lr
        JOIN public."LeaveType" lt ON lt."Id" = lr."LeaveTypeId"
        CROSS JOIN LATERAL generate_series(lr."FromDate", lr."ToDate", INTERVAL '1 day') AS d
        WHERE lr."Status" = 1
    ),
    holiday_data AS (
        SELECT h."HolidayDate", h."Id" AS holiday_id, h."HolidayName"::text AS holiday_name
        FROM public."Holiday" h
        WHERE h."IsActive" = TRUE
    )
    SELECT
        g.employee_id,
        g.att_date AS attendance_date,
        COALESCE(a."Status", CASE 
            WHEN hd.holiday_id IS NOT NULL THEN 4
            WHEN EXTRACT(DOW FROM g.att_date) = 0 THEN 5
            WHEN ld.leave_type_id IS NOT NULL THEN 3
            WHEN g.att_date < CURRENT_DATE THEN 2
            ELSE 0
        END) AS attendance_status,
        CASE 
            WHEN a."Status" = 1 THEN 'Present'
            WHEN a."Status" = 2 THEN 'Absent'
            WHEN a."Status" = 3 THEN 'On Leave'
            WHEN a."Status" = 4 THEN 'Holiday'
            WHEN a."Status" = 5 THEN 'Weekend'
            WHEN hd.holiday_id IS NOT NULL THEN 'Holiday'
            WHEN EXTRACT(DOW FROM g.att_date) = 0 THEN 'Weekend'
            WHEN ld.leave_type_id IS NOT NULL THEN 'On Leave'
            WHEN g.att_date < CURRENT_DATE THEN 'Absent'
            ELSE 'Pending'
        END AS status_name,
        a."CheckInTime",
        a."CheckOutTime",
        a."CheckInLatitude",
        a."CheckInLongitude",
        a."CheckInDistanceMeters",
        a."CheckOutLatitude",
        a."CheckOutLongitude",
        a."CheckOutDistanceMeters",
        COALESCE(a."WorkedMinutes", 0),
        COALESCE(a."IsLate", false),
        COALESCE(a."LateMinutes", 0),
        COALESCE(a."IsEarlyDeparture", false),
        COALESCE(a."EarlyDepartureMinutes", 0),
        COALESCE(a."OTMinutes", 0),
        ld.leave_type_id,
        ld.leave_type_name,
        hd.holiday_id,
        hd.holiday_name
    FROM grid g
    LEFT JOIN public."Attendance" a ON a."EmployeeId" = g.employee_id AND a."AttendanceDate" = g.att_date
    LEFT JOIN leave_data ld ON ld.employee_id = g.employee_id AND ld.leave_date = g.att_date
    LEFT JOIN holiday_data hd ON hd."HolidayDate" = g.att_date
    ORDER BY g.employee_id, g.att_date DESC;
END;
$function$;

